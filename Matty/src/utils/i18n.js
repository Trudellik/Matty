/** Translate a key, with optional {placeholder} interpolation */
export function t(locale, key, vars) {
  let str = translations[locale]?.[key] ?? translations.en[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v)
    })
  }
  return str
}

